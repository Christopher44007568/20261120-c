def _pixel(canvas, x: int, y: int, color: tuple[int, int, int]) -> None:
    if 0 <= x < canvas.width and 0 <= y < canvas.height:
        offset = (y * canvas.width + x) * 3
        canvas.pixels[offset : offset + 3] = bytes(color)


class Canvas:
    def __init__(self, width: int, height: int, background=(12, 16, 24)):
        self.width = width
        self.height = height
        self.pixels = bytearray(background * (width * height))

    def rect(self, x: int, y: int, w: int, h: int, color) -> None:
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(self.width, x + w), min(self.height, y + h)
        if x1 <= x0 or y1 <= y0:
            return
        row = bytes(color) * (x1 - x0)
        for sy in range(y0, y1):
            offset = (sy * self.width + x0) * 3
            self.pixels[offset : offset + len(row)] = row

    def outline(self, x: int, y: int, w: int, h: int, color, thickness=4) -> None:
        self.rect(x, y, w, thickness, color)
        self.rect(x, y + h - thickness, w, thickness, color)
        self.rect(x, y, thickness, h, color)
        self.rect(x + w - thickness, y, thickness, h, color)

    def line(self, x0: int, y0: int, x1: int, y1: int, color, thickness=2) -> None:
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx + dy
        while True:
            if thickness <= 1:
                _pixel(self, x0, y0, color)
            else:
                self.rect(x0 - thickness // 2, y0 - thickness // 2, thickness, thickness, color)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    def text_size(self, text: str, scale: int = 2) -> tuple[int, int]:
        return (len(text) * 6 * scale - scale, 7 * scale)

    def text(self, x: int, y: int, text: str, color=(225, 231, 240), scale=2) -> None:
        cursor = x
        for char in text.upper():
            glyph = FONT.get(char, FONT[" "])
            for gy, row in enumerate(glyph):
                for gx, bit in enumerate(row):
                    if bit == "1":
                        self.rect(cursor + gx * scale, y + gy * scale, scale, scale, color)
            cursor += 6 * scale

    def blit(self, image: Canvas, x: int, y: int, width: int, height: int) -> None:
        for dy in range(height):
            sy = min(image.height - 1, dy * image.height // height)
            for dx in range(width):
                sx = min(image.width - 1, dx * image.width // width)
                src = (sy * image.width + sx) * 3
                dst = ((y + dy) * self.width + x + dx) * 3
                self.pixels[dst : dst + 3] = image.pixels[src : src + 3]

    def crop(self, x: int, y: int, w: int, h: int) -> "Canvas":
        out = Canvas(w, h)
        for row in range(h):
            src = ((y + row) * self.width + x) * 3
            out.pixels[row * w * 3 : (row + 1) * w * 3] = self.pixels[src : src + w * 3]
        return out

    def save(self, path: str | Path) -> None:
        write_png(path, self.width, self.height, self.pixels)


def load_canvas(path: str | Path) -> Canvas:
    width, height, pixels = read_ppm(path)
    canvas = Canvas(width, height)
    canvas.pixels = pixels
    return canvas


def ppm(path: str | Path) -> Canvas:
    return load_canvas(path)

